create table if not exists public.eps_modulos (
  id       bigint generated by default as identity primary key,
  trayecto text not null,
  nivel    integer not null check (nivel between 1 and 4),
  nombre   text not null,
  orden    integer not null default 0
);
create unique index if not exists eps_modulos_uk on public.eps_modulos (trayecto, nivel, nombre);

create table if not exists public.eps_ptf (
  estudiante_id bigint primary key references public.eps_estudiantes(id) on delete cascade,
  oferta     text,
  turno      text,
  anio       integer,
  textos     jsonb not null default '{}'::jsonb,   -- diagnóstico, organización, estrategias, evaluación
  notas      jsonb not null default '{}'::jsonb,   -- {"1":{"fp":{"MODULO":[5 valores]},"gen":{"Matemática":[5]}}, ...}
  pendientes jsonb not null default '{}'::jsonb,   -- {"nivel":"III","Matemática":"texto"}
  observaciones text,
  updated_at timestamptz not null default now()
);

alter table public.eps_modulos enable row level security;
alter table public.eps_ptf enable row level security;
drop policy if exists eps_modulos_all on public.eps_modulos;
create policy eps_modulos_all on public.eps_modulos for all using (public.eps_puede()) with check (public.eps_puede());
drop policy if exists eps_ptf_all on public.eps_ptf;
create policy eps_ptf_all on public.eps_ptf for all using (public.eps_puede()) with check (public.eps_puede());
