-- PASO 54 — LICENCIAS DOCENTES (administrativas, médicas y paros) + FERIADOS + CICLO LECTIVO
-- Ejecutar UNA vez en Supabase → SQL Editor (se puede repetir sin romper nada).
--
-- Solo Dirección y Secretaría (es_admin_total) pueden VER y CARGAR. Docentes, estudiantes y
-- el resto del personal NO tienen acceso a estas tablas.
--
-- · licencias_docentes : una fila por licencia/paro con fechas desde-hasta. Los días hábiles
--                        se calculan en pantalla (lunes a viernes menos feriados cargados).
-- · feriados           : nacionales, provinciales, municipales y asuetos. Editable desde la pantalla.
-- · licencias_ciclo    : inicio y fin del ciclo lectivo de cada año (para contar sus días hábiles).
-- =====================================================================================

create table if not exists public.licencias_docentes (
  id          bigint generated by default as identity primary key,
  docente_id  uuid not null references public.profiles(id) on delete cascade,
  tipo        text not null check (tipo in ('administrativa', 'medica', 'paro')),
  desde       date not null,
  hasta       date not null,
  articulo    text,        -- artículo / causal / tipo (ej. "Art. 114 inc. c", "Enfermedad", "Estudio")
  detalle     text check (char_length(detalle) <= 500),
  creado_por  uuid default auth.uid(),
  creado_por_nombre text,
  created_at  timestamptz not null default now(),
  constraint licencias_docentes_fechas check (hasta >= desde)
);
create index if not exists licencias_docentes_docente_idx on public.licencias_docentes (docente_id, desde);

create table if not exists public.feriados (
  id          bigint generated by default as identity primary key,
  fecha       date not null,
  nombre      text not null,
  ambito      text not null default 'nacional' check (ambito in ('nacional', 'provincial', 'municipal', 'asueto')),
  created_at  timestamptz not null default now(),
  unique (fecha, ambito)
);

create table if not exists public.licencias_ciclo (
  ciclo   integer primary key,
  inicio  date not null,
  fin     date not null,
  constraint licencias_ciclo_fechas check (fin >= inicio)
);

alter table public.licencias_docentes enable row level security;
alter table public.feriados enable row level security;
alter table public.licencias_ciclo enable row level security;

drop policy if exists licencias_docentes_todo on public.licencias_docentes;
drop policy if exists feriados_todo on public.feriados;
drop policy if exists licencias_ciclo_todo on public.licencias_ciclo;
create policy licencias_docentes_todo on public.licencias_docentes for all to authenticated
  using (public.es_admin_total()) with check (public.es_admin_total());
create policy feriados_todo on public.feriados for all to authenticated
  using (public.es_admin_total()) with check (public.es_admin_total());
create policy licencias_ciclo_todo on public.licencias_ciclo for all to authenticated
  using (public.es_admin_total()) with check (public.es_admin_total());

-- Docentes para el selector (el rol docente activo). Solo Dirección/Secretaría.
create or replace function public.licencias_listar_docentes()
returns table (id uuid, dni text, apellido text, nombre text)
language sql stable security definer set search_path = public as $$
  select p.id, p.dni, p.apellido, p.nombre
  from public.profiles p
  where public.es_admin_total()
    and lower(p.rol::text) = 'docente'
    and upper(coalesce(p.estado, 'ACTIVO')) = 'ACTIVO'
  order by p.apellido, p.nombre;
$$;

