create table if not exists public.eps_asistencia (
  id            bigint generated by default as identity primary key,
  estudiante_id bigint not null references public.eps_estudiantes(id) on delete cascade,
  mes           text not null check (mes ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),   -- 'YYYY-MM'
  dias_clase    integer not null check (dias_clase >= 0),
  presentes     integer not null check (presentes >= 0),
  unique (estudiante_id, mes),
  constraint eps_asistencia_pres check (presentes <= dias_clase)
);
alter table public.eps_asistencia enable row level security;
drop policy if exists eps_asistencia_all on public.eps_asistencia;
create policy eps_asistencia_all on public.eps_asistencia for all using (public.eps_puede()) with check (public.eps_puede());
