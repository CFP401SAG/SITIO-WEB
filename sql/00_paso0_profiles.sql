-- -----------------------------------------------------------------------------
-- 0.1  profiles — una fila por cuenta (Auth + rol + estado)
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id         uuid primary key,
  dni        text not null,
  nombre     text not null,
  rol        text not null,
  created_at timestamptz default now(),
  estado     text default 'ACTIVO',
  apellido   text,
  email      text
);
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'profiles_dni_key') then
    alter table public.profiles add constraint profiles_dni_key unique (dni);
  end if;
end $$;

-- -----------------------------------------------------------------------------
-- 0.2  trayectos — los cursos / especialidades
-- -----------------------------------------------------------------------------
create table if not exists public.trayectos (
  id                   bigint generated by default as identity primary key,
  nombre               text not null,
  sector               text,
  descripcion          text,
  created_at           timestamptz not null default timezone('utc'::text, now()),
  requisitos           text,
  certificacion        text,
  resolucion           text,
  ciclo_lectivo        integer default extract(year from now())::int,
  docente_user         text,
  computa_asistencia   boolean not null default true,
  horas                integer,
  sede                 text default 'sede',
  lugar_dictado        text,
  localidad            text default 'San Andrés de Giles',
  fecha_inicio         date,
  fecha_cierre         date,
  horario              text,
  tipo_certificacion   text,
  codigo_catalogo      text,
  acto_administrativo  text,
  horario_dias         jsonb,
  horas_catedra        integer,
  obs_planilla         text
);
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'trayectos_horas_check') then
    alter table public.trayectos add constraint trayectos_horas_check
      check (horas is null or (horas >= 1 and horas <= 5000));
  end if;
end $$;

-- -----------------------------------------------------------------------------
-- 0.3  modulos — unidades dentro de cada trayecto
-- -----------------------------------------------------------------------------
create table if not exists public.modulos (
  id           bigint generated by default as identity primary key,
  trayecto_id  bigint references public.trayectos(id) on delete cascade,
  nombre       text not null,
  codigo       text,
  fecha_inicio date,
  fecha_fin    date,
  created_at   timestamptz not null default timezone('utc'::text, now())
);

-- -----------------------------------------------------------------------------
-- 0.4  clases — material, trabajos prácticos, evaluaciones, etc.
-- -----------------------------------------------------------------------------
create table if not exists public.clases (
  id                 bigint generated by default as identity primary key,
  trayecto_id        bigint references public.trayectos(id) on delete cascade,
  titulo             text not null,
  descripcion        text,
  contenido          jsonb,
  url_recurso        text,
  orden              integer default 1,
  creado_en          timestamptz default now(),
  modulo_id          bigint references public.modulos(id) on delete set null,
  estudiante_user    text,
  tipo               text not null default 'material',
  fecha_publicacion  date,
  fecha_limite       timestamptz,
  url_actividad      text,
  es_evaluacion      boolean not null default false,
  calificable        boolean not null default true
);

-- -----------------------------------------------------------------------------
