--   • Lo ven y cargan: Dirección y Secretaría (todos los trayectos) y el docente o suplente
--     del trayecto (solo sus trayectos).
--   • No se modifica: si hubo un error se borra (solo quien lo cargó o la Dirección/Secretaría).
--   • Queda en la auditoría como cualquier otro cambio.
