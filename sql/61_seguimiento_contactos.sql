create table if not exists public.seguimiento_contactos (
  id              bigint generated by default as identity primary key,
  trayecto_id     bigint not null references public.trayectos(id) on delete cascade,
  estudiante_user text   not null,
  fecha           timestamptz not null default now(),
  tipo            text not null check (tipo in ('llamada', 'whatsapp', 'mensaje', 'entrevista', 'otro')),
  resultado       text not null check (resultado in ('contactado', 'no_responde', 'vuelve', 'abandona', 'otro')),
  nota            text check (char_length(nota) <= 300),
  creado_por      uuid not null default auth.uid(),
  creado_nombre   text check (char_length(creado_nombre) <= 120)
);
create index if not exists seguimiento_contactos_idx on public.seguimiento_contactos (trayecto_id, estudiante_user, fecha desc);

alter table public.seguimiento_contactos enable row level security;

drop policy if exists seg_contactos_select on public.seguimiento_contactos;
create policy seg_contactos_select on public.seguimiento_contactos for select to authenticated
  using (public.es_admin() or public.es_docente_de(trayecto_id));

drop policy if exists seg_contactos_insert on public.seguimiento_contactos;
create policy seg_contactos_insert on public.seguimiento_contactos for insert to authenticated
  with check (creado_por = auth.uid() and (public.es_admin() or public.es_docente_de(trayecto_id)));

drop policy if exists seg_contactos_delete on public.seguimiento_contactos;
create policy seg_contactos_delete on public.seguimiento_contactos for delete to authenticated
  using (public.es_admin() or (creado_por = auth.uid() and public.es_docente_de(trayecto_id)));

revoke all on public.seguimiento_contactos from anon;
grant select, insert, delete on public.seguimiento_contactos to authenticated;

drop trigger if exists trg_auditoria on public.seguimiento_contactos;
create trigger trg_auditoria after insert or update or delete on public.seguimiento_contactos
  for each row execute function public.registrar_auditoria();
