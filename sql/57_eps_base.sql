-- Tablas separadas (eps_*): NO toca nada de Formación Profesional.
-- Acceso: Dirección y Secretaría (es_admin_total) + la coordinadora EPS si tiene cuenta
-- vinculada en eps_personal.user_id.
-- =====================================================================================

create table if not exists public.eps_personal (
  id        bigint generated by default as identity primary key,
  apellido  text not null,
  nombre    text not null,
  dni       text,
  funcion   text not null check (funcion in ('coordinador','docente_general','docente_especifica')),
  area      text,          -- materia (formación general) o trayecto/módulo (formación específica)
  telefono  text,
  email     text,
  user_id   uuid references public.profiles(id) on delete set null,   -- cuenta de la coordinadora (opcional)
  activo    boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.eps_estudiantes (
  id            bigint generated by default as identity primary key,
  dni           text not null unique,
  apellido      text not null,
  nombre        text not null,
  fecha_nac     date,
  domicilio     text,
  telefono      text,
  email         text,
  tutor         text,
  escuela_origen text,
  anio_desvinculo integer,
  trayecto      text,
  cohorte       integer default extract(year from now())::int,
  fecha_ingreso date,
  estado        text not null default 'activo' check (estado in ('activo','baja','egresado')),
  observaciones text,
  created_at    timestamptz not null default now()
);

create or replace function public.eps_puede() returns boolean
language sql stable security definer set search_path = public as $$
  select public.es_admin_total()
      or exists (select 1 from public.eps_personal p
                 where p.user_id = auth.uid() and p.funcion = 'coordinador' and p.activo);
$$;

alter table public.eps_personal enable row level security;
alter table public.eps_estudiantes enable row level security;

drop policy if exists eps_personal_all on public.eps_personal;
create policy eps_personal_all on public.eps_personal for all
  using (public.eps_puede()) with check (public.es_admin_total());
drop policy if exists eps_personal_lee on public.eps_personal;

drop policy if exists eps_estudiantes_all on public.eps_estudiantes;
create policy eps_estudiantes_all on public.eps_estudiantes for all
  using (public.eps_puede()) with check (public.eps_puede());
