-- PASO 61 — ENCUESTA / AUTOEVALUACIÓN DE CIERRE DEL TRAYECTO
-- Ejecutar UNA vez en Supabase → SQL Editor (se puede repetir sin romper nada).
--
-- · La encuesta le aparece sola a cada estudiante activo 15 días antes del cierre del trayecto
--   (trayectos.fecha_cierre). Las preguntas viven en js/encuesta_final.js.
-- · Cada estudiante responde UNA vez por trayecto y solo ve la suya.
-- · Docentes y Dirección/Secretaría NO leen respuestas individuales: piden un resumen
--   (función encuesta_final_resumen) que devuelve las respuestas SIN el DNI. Para proteger el
--   anonimato, a un docente no se le muestra nada hasta que haya 3 respuestas o más.
-- =====================================================================================

create table if not exists public.encuestas_finales (
  id              bigint generated by default as identity primary key,
  trayecto_id     bigint not null references public.trayectos(id) on delete cascade,
  estudiante_user text not null,                       -- DNI (solo para evitar duplicados)
  respuestas      jsonb not null default '{}'::jsonb,  -- {"p_clave": 1..5 | "texto" | ["a","b"]}
  comentario      text check (comentario is null or char_length(comentario) <= 1000),
  version         integer not null default 1,
  created_at      timestamptz not null default now(),
  unique (trayecto_id, estudiante_user)
);

alter table public.encuestas_finales enable row level security;

drop policy if exists encuestas_finales_select on public.encuestas_finales;
drop policy if exists encuestas_finales_insert on public.encuestas_finales;
-- cada estudiante ve solo la suya (para saber si ya respondió)
create policy encuestas_finales_select on public.encuestas_finales for select to authenticated
  using (estudiante_user = public.mi_dni());
-- y solo puede responder si está inscripto (sin baja) en ese trayecto
create policy encuestas_finales_insert on public.encuestas_finales for insert to authenticated
  with check (
    estudiante_user = public.mi_dni()
    and exists (select 1 from public.inscripciones i
                where i.trayecto_id = encuestas_finales.trayecto_id
                  and i.estudiante_user = public.mi_dni()
                  and upper(coalesce(i.estado, 'ACTIVA')) <> 'BAJA')
  );

-- Resumen anónimo. p_trayecto = null → todos los trayectos que puede ver quien consulta.
create or replace function public.encuesta_final_resumen(p_trayecto bigint default null)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  admin boolean := public.es_admin();
  res jsonb;
begin
  if not (admin or public.es_docente()) then
    raise exception 'No autorizado';
  end if;

  select coalesce(jsonb_agg(x order by x->>'nombre'), '[]'::jsonb) into res
  from (
    select jsonb_build_object(
      'trayecto_id', t.id,
      'nombre', t.nombre,
      'ciclo', t.ciclo_lectivo,
      'fecha_cierre', t.fecha_cierre,
      'matriculados', (select count(*) from public.inscripciones i
                        where i.trayecto_id = t.id and upper(coalesce(i.estado, 'ACTIVA')) <> 'BAJA'),
      'n', (select count(*) from public.encuestas_finales e where e.trayecto_id = t.id),
      -- a un docente se le oculta el detalle hasta que haya al menos 3 respuestas
      'oculto', (not admin) and (select count(*) from public.encuestas_finales e where e.trayecto_id = t.id) < 3,
      'respuestas', case
        when (not admin) and (select count(*) from public.encuestas_finales e where e.trayecto_id = t.id) < 3 then '[]'::jsonb
        else coalesce((select jsonb_agg(e.respuestas || jsonb_build_object('_comentario', e.comentario))
                         from public.encuestas_finales e where e.trayecto_id = t.id), '[]'::jsonb) end
    ) as x
    from public.trayectos t
    where (p_trayecto is null or t.id = p_trayecto)
      and (admin or public.es_docente_de(t.id))
  ) q;
  return res;
end $$;

revoke all on function public.encuesta_final_resumen(bigint) from public;
grant execute on function public.encuesta_final_resumen(bigint) to authenticated;
